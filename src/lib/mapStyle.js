export async function ensureMapImages(mapInstance) {
  await Promise.all([
    ensureSingleMapImage(
      mapInstance,
      MAP_ICON_IDS.waterReservoir,
      new URL(MAP_ICON_PATHS.waterReservoir, window.location.origin).toString(),
    ),
    ensureSingleMapImage(
      mapInstance,
      MAP_ICON_IDS.powerSubstation,
      new URL(MAP_ICON_PATHS.powerSubstation, window.location.origin).toString(),
    ),
    ensureSingleMapImage(
      mapInstance,
      MAP_ICON_IDS.hospital,
      new URL(MAP_ICON_PATHS.hospital, window.location.origin).toString(),
    ),
    ensureSingleMapImage(
      mapInstance,
      MAP_ICON_IDS.fireStation,
      new URL(MAP_ICON_PATHS.fireStation, window.location.origin).toString(),
    ),
    ensureSingleMapImage(
      mapInstance,
      MAP_ICON_IDS.policeStation,
      new URL(MAP_ICON_PATHS.policeStation, window.location.origin).toString(),
    ),
  ]);
}

async function ensureSingleMapImage(mapInstance, imageId, imageUrl) {
  if (mapInstance.hasImage(imageId)) {
    return;
  }

  const response = await fetch(imageUrl);

  if (!response.ok) {
    throw new Error(`Failed to load map image: ${imageUrl}`);
  }

  const imageBlob = await response.blob();
  const imageBitmap = await createImageBitmap(imageBlob);

  if (!mapInstance.hasImage(imageId)) {
    mapInstance.addImage(imageId, imageBitmap);
  }
}

export function attachCursor(mapInstance, layerId, pickModeRef) {
  mapInstance.on("mouseenter", layerId, () => {
    mapInstance.getCanvas().style.cursor = pickModeRef.current ? "crosshair" : "pointer";
  });

  mapInstance.on("mouseleave", layerId, () => {
    mapInstance.getCanvas().style.cursor = pickModeRef.current ? "crosshair" : "";
  });
}
