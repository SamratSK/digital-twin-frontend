export function getPmtilesProtocol() {
  if (!globalThis.__bengaluruPmtilesProtocol) {
    const protocol = new Protocol({ metadata: true });
    maplibregl.addProtocol("pmtiles", protocol.tile);
    globalThis.__bengaluruPmtilesProtocol = protocol;
  }

  return globalThis.__bengaluruPmtilesProtocol;
}

export function getMapPadding() {
  if (window.innerWidth < 720) {
    return { top: 28, right: 16, bottom: 16, left: 16 };
  }

  return { top: 18, right: 18, bottom: 18, left: 18 };
}

